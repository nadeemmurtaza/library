import fs from 'node:fs'
import path from 'node:path'

const SOURCE = 'daisyui@5.7.50'
const LICENSE = 'MIT'
const items = []
const push = (type, name, file) =>
  items.push({ type, name, path: file.split(path.sep).join('/'), source: SOURCE, license: LICENSE })

const flat = (type, dir) => {
  for (const f of fs.readdirSync(dir)) {
    if (f.endsWith('.css')) push(type, path.basename(f, '.css'), path.join(dir, f))
  }
}

for (const c of fs.readdirSync('styles/components', { withFileTypes: true })) {
  if (!c.isDirectory()) continue
  push('component', c.name, path.join('styles/components', c.name, `${c.name}.css`))
  const ex = path.join('styles/components', c.name, `${c.name}.example.html`)
  if (fs.existsSync(ex)) items[items.length - 1].example = ex.split(path.sep).join('/')
}
flat('base', 'styles/base')
flat('utility', 'styles/utilities')
flat('theme', 'tokens/themes')
flat('color', 'tokens/colors')

for (const t of fs.readdirSync('design-trends', { withFileTypes: true })) {
  if (!t.isDirectory()) continue
  const dir = path.join('design-trends', t.name)
  const f = (suffix) => path.join(dir, `${t.name}${suffix}`).split(path.sep).join('/')
  items.push({
    type: 'design-trend',
    name: t.name,
    path: f('.md'),
    demo: f('.demo.html'),
    demoCss: f('.demo.css'),
    screenshot: fs.readdirSync(dir).map((n) => `${dir}/${n}`.split(path.sep).join('/')).find((n) => n.includes('.screenshot.')),
    source: 'trends.daisyui.com',
  })
}

// Generic scan: any file dropped into these dirs becomes a catalog item, typed by its dir.
const GENERIC = [
  'assets', 'schemas', 'functions', 'utils', 'hooks', 'lib', 'scripts', 'snippets', 'templates',
  'constants', 'types', 'providers', 'components/ui', 'components/common', 'components/layout', 'components/patterns',
]
const known = new Set(items.map((i) => i.path))
const walk = (dir) => fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
  const p = path.join(dir, e.name)
  return e.isDirectory() ? walk(p) : [p]
})
for (const dir of GENERIC) {
  if (!fs.existsSync(dir)) continue
  for (const file of walk(dir)) {
    const rel = file.split(path.sep).join('/')
    if (path.basename(file) === '.gitkeep' || known.has(rel)) continue
    items.push({ type: dir.replace('/', '-'), name: rel.slice(dir.length + 1), path: rel, source: 'local' })
  }
}

const themeNames = [...items.filter((i) => i.type === 'theme').map((i) => i.name), 'brand', 'brand-dark']
fs.writeFileSync(
  'tokens/themes/index.ts',
  `/** Every theme name usable in data-theme. Generated by scripts/build-catalog.mjs. */
export const themeNames = ${JSON.stringify(themeNames)} as const

export type ThemeName = (typeof themeNames)[number]
`,
)
items.push(
  { type: 'config', name: 'brand', path: 'config/brand.ts', source: 'local' },
  { type: 'token', name: 'tokens', path: 'tokens/tokens.css', source: 'local' },
  { type: 'theme', name: 'brand', path: 'tokens/brand-theme.css', source: 'local' },
  { type: 'entry', name: 'index', path: 'styles/index.css', source: 'local' },
)

fs.writeFileSync('registry/catalog.json', JSON.stringify({ version: 1, items }, null, 2))
const counts = {}
for (const i of items) counts[i.type] = (counts[i.type] || 0) + 1
console.log(counts)
